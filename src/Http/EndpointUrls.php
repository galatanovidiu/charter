<?php
/**
 * Public OAuth endpoint URL projection.
 *
 * @package GalatanOvidiu\Charter
 */

declare(strict_types=1);

namespace GalatanOvidiu\Charter\Http;

/**
 * Builds every public endpoint from the one stored canonical issuer.
 *
 * @since 0.1.0
 */
final class EndpointUrls {

	/**
	 * Creates the endpoint projector.
	 *
	 * @since 0.1.0
	 *
	 * @param string $issuer Exact canonical issuer.
	 */
	public function __construct(
		private readonly string $issuer
	) {
	}

	/**
	 * Returns the RFC 8414 metadata URL.
	 *
	 * @since 0.1.0
	 */
	public function authorizationServerMetadata(): string {
		return $this->issuer . '/.well-known/oauth-authorization-server';
	}

	/**
	 * Returns the root RFC 9728 metadata URL.
	 *
	 * @since 0.1.0
	 */
	public function protectedResourceMetadata(): string {
		return $this->issuer . '/.well-known/oauth-protected-resource';
	}

	/**
	 * Returns the browser authorization endpoint.
	 *
	 * @since 0.1.0
	 */
	public function authorizationEndpoint(): string {
		return $this->replaceOrigin( admin_url( 'admin-post.php?action=charter_oauth_authorize' ) );
	}

	/**
	 * Returns the token endpoint.
	 *
	 * @since 0.1.0
	 */
	public function tokenEndpoint(): string {
		return $this->replaceOrigin( rest_url( 'charter/v1/token' ) );
	}

	/**
	 * Returns the RFC 7009 token revocation endpoint.
	 *
	 * @since 0.1.0
	 */
	public function revocationEndpoint(): string {
		return $this->replaceOrigin( rest_url( 'charter/v1/revoke' ) );
	}

	/**
	 * Returns the RFC 7591 Dynamic Client Registration endpoint.
	 *
	 * @since 0.1.0
	 */
	public function registrationEndpoint(): string {
		return $this->replaceOrigin( rest_url( 'charter/v1/register' ) );
	}

	/**
	 * Replaces a WordPress-generated origin while retaining its routed path.
	 *
	 * @since 0.1.0
	 *
	 * @param string $localUrl URL generated by WordPress configuration.
	 */
	private function replaceOrigin( string $localUrl ): string {
		$parts = wp_parse_url( $localUrl );
		$path  = is_string( $parts['path'] ?? null ) ? $parts['path'] : '/';
		$query = is_string( $parts['query'] ?? null ) ? '?' . $parts['query'] : '';

		return $this->issuer . '/' . ltrim( $path, '/' ) . $query;
	}
}
